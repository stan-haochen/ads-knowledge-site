// Optional authoring utility. dist/ is committed and needs no build to serve.
// npm install --no-save --package-lock=false --ignore-scripts marked@15.0.12 katex@0.16.22
import {readFile, writeFile, mkdir, copyFile, readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve, dirname} from 'node:path';
import {Marked} from 'marked';
import katex from 'katex';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const directory = resolve(root, 'dist/articles/amortized-analysis');
const source = await readFile(resolve(directory, 'index.md'));
const sha = createHash('sha256').update(source).digest('hex');
const escape = text => text.replace(/[&<>"']/g, char => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[char]));
const math = (text, displayMode) => katex.renderToString(text, {
  displayMode, throwOnError: true, strict: false, trust: false,
  output: 'htmlAndMathml', maxExpand: 1000
});
const marked = new Marked({gfm: true});
marked.use({extensions: [{
  name: 'articleMath', level: 'inline',
  start: text => text.indexOf('$'),
  tokenizer(text) {
    const match = /^\$([^$\n]+)\$/.exec(text);
    if (match) return {type: 'articleMath', raw: match[0], text: match[1]};
  },
  renderer: token => `<span class="aa-inline-math">${math(token.text, false)}</span>`
}], renderer: {
  code({text, lang}) {
    if (lang !== 'math') throw new Error(`Unexpected code block: ${lang}`);
    return `<div class="aa-equation" tabindex="0" aria-label="势能法恒等式">${math(`\\begin{gathered}${text}\\end{gathered}`, true)}</div>\n`;
  },
  image({href}) {
    if (href !== './splay.png') throw new Error(`Unexpected illustration: ${href}`);
    return '<a class="aa-diagram" href="articles/amortized-analysis/splay.svg" target="_blank" rel="noopener" aria-label="打开 Splay 三种旋转示意图"><img src="articles/amortized-analysis/splay.svg" alt="Zig、Zig-Zig 与 Zig-Zag 旋转前后；x、y、z 和 A–D 子树与原图对应" width="1080" height="960" loading="lazy"></a>';
  },
  link({href, tokens}) {
    if (!/^https:\/\//.test(href)) throw new Error(`Unexpected reference URL: ${href}`);
    return `<a href="${escape(href)}" target="_blank" rel="noopener">${this.parser.parseInline(tokens)}</a>`;
  }
}});

// Promote the author's existing labels to headings, keeping their words intact.
const sections = [
  ['（1）聚合法', 'aggregate', 2], ['（2）记账法', 'accounting', 2],
  ['（3）势能法', 'potential', 2], ['a）`MultiPop`模型', 'multipop', 2],
  ['b）`Move-To-Front`（下称MTF）线性搜索算法', 'mtf', 2], ['c）splay树', 'splay', 2],
  ['然后计算Zig情况：', 'zig', 3], ['最后计算Zig-Zag情况：', 'zigzag', 3]
];
let body = marked.parse(source.toString('utf8'));
for (const [label, id, level] of sections) {
  const text = marked.parseInline(label);
  const paragraph = `<p>${text}</p>`;
  if (!body.includes(paragraph)) throw new Error(`Missing section: ${label}`);
  body = body.replace(paragraph, `<h${level} id="aa-${id}">${text}</h${level}>`);
}
body = body.replace('<h1>摊还分析</h1>', '<h1 id="aa-title">摊还分析</h1>')
  .replace('<h3>Reference</h3>', '<h2 id="aa-references">Reference</h2>');
await writeFile(resolve(directory, 'article.html'), `<!-- Source SHA-256: ${sha}; generated by scripts/render-amortized-analysis.mjs -->\n${body}`);

// Vendor CSS and fonts only. All formulas are already HTML + accessible MathML.
const vendor = resolve(root, 'dist/vendor/katex');
await mkdir(resolve(vendor, 'fonts'), {recursive: true});
const katexRoot = resolve(root, 'node_modules/katex');
const css = (await readFile(resolve(katexRoot, 'dist/katex.min.css'), 'utf8'))
  .replace(/,url\(fonts\/[^)]+\.(?:woff|ttf)\) format\("(?:woff|truetype)"\)/g, '');
await writeFile(resolve(vendor, 'katex.min.css'), css);
await copyFile(resolve(katexRoot, 'LICENSE'), resolve(vendor, 'LICENSE'));
for (const name of await readdir(resolve(katexRoot, 'dist/fonts'))) {
  if (name.endsWith('.woff2')) await copyFile(resolve(katexRoot, 'dist/fonts', name), resolve(vendor, 'fonts', name));
}
console.log(`Rendered article without editing index.md. SHA-256: ${sha}`);
